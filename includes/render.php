<?php
/**
 * Frontend rendering of inline tokens.
 *
 * Each token is resolved against the networks that are both selected on that
 * instance and currently enabled — the intersection computed at render time, so
 * toggling a network in settings changes every post at once. Hashtags and
 * mentions share the same shape: one target → a direct link; several → a pane;
 * none → the local archive or plain text (per the setting).
 *
 *  - Hashtag tokens: the identifier is the term slug; the visible #text is kept,
 *    and a single/multiple target links directly / opens a pane of network names.
 *  - Mention tokens: the identifier is the per-network handle stored on the term
 *    (read from TermConnect). A single external profile renders inline as the
 *    network icon + handle (replacing the local @name); several open a pane of
 *    icon + handle rows. A link to the local profile keeps the @name.
 *
 * @package SocialHashtagsMentions
 * @since 1.0.0
 */

if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

add_filter( 'the_content', 'sh_render_tokens', 20 );
add_action( 'wp_enqueue_scripts', 'sh_enqueue_frontend_assets' );

/**
 * Enqueues the frontend stylesheet for token badges and the Blogosphere section.
 *
 * @since 1.0.0
 */
function sh_enqueue_frontend_assets(): void {
    wp_enqueue_style(
        'social-hashtags-mentions',
        SH_PLUGIN_URL . 'assets/css/social-hashtags-mentions.css',
        array( 'dashicons' ),
        SH_VERSION
    );
    wp_enqueue_script(
        'social-hashtags-mentions',
        SH_PLUGIN_URL . 'assets/js/sh-frontend.js',
        array(),
        SH_VERSION,
        true
    );
}

/**
 * Augments inline tokens in post content with network badges.
 *
 * @since 1.0.0
 * @param string $content Post content.
 * @return string
 */
function sh_render_tokens( string $content ): string {
    if ( false === strpos( $content, 'data-sh-tax' ) ) {
        return $content;
    }

    // Excerpts are generated by running the_content and stripping tags; rendered network
    // panes would leave their labels ("Instagram Bluesky …") in the excerpt text. Keep
    // the plain token anchors there so only "#tag" / "@name" survives.
    if ( doing_filter( 'get_the_excerpt' ) || doing_filter( 'wp_trim_excerpt' ) ) {
        return $content;
    }

    // Attribute portion is quote-aware so a literal '>' inside a quoted attribute
    // value (e.g. title="a > b") doesn't truncate the match early.
    return (string) preg_replace_callback(
        '/<a\b((?:[^>"\']|"[^"]*"|\'[^\']*\')*)>(.*?)<\/a>/is',
        'sh_render_token_callback',
        $content
    );
}

/**
 * preg_replace_callback handler for a single anchor.
 *
 * @since 1.0.0
 * @param array $match [ full, attrs, inner ]
 * @return string
 */
function sh_render_token_callback( array $match ): string {
    $attrs = $match[1];
    $inner = $match[2];

    if ( false === strpos( $attrs, 'data-sh-tax' ) ) {
        return $match[0];
    }

    // Idempotency guard: skip anchors already processed, so a second the_content
    // pass (excerpt builders, page builders, etc.) doesn't duplicate badges/panes.
    if ( false !== strpos( $attrs, 'sh-rendered' ) ) {
        return $match[0];
    }

    $taxonomy = sh_token_attr( $attrs, 'data-sh-tax' );
    if ( ! in_array( $taxonomy, sh_taxonomies(), true ) ) {
        return $match[0];
    }

    $term = sh_resolve_token_term( $attrs, $taxonomy );
    if ( ! ( $term instanceof WP_Term ) ) {
        return $match[0];
    }

    $universe = ( 'hashtag' === $taxonomy )
        ? sh_get_enabled_networks( 'hashtag' )
        : sh_mention_universe( $term );
    $selected = sh_token_selected_networks( $attrs, $universe );
    $attrs    = sh_add_class( $attrs, 'sh-rendered' );

    if ( 'hashtag' === $taxonomy ) {
        return sh_render_hashtag_token( $attrs, $inner, $term, $selected );
    }

    return sh_render_mention_token( $attrs, $inner, $term, $selected );
}

/**
 * Renders a hashtag token: direct link (one target), pane (many), or
 * archive/plain (none), per the per-instance ∩ enabled network targets.
 *
 * @since 1.0.0
 * @param string   $attrs    Anchor attribute string.
 * @param string   $inner    Anchor inner HTML (the visible #token).
 * @param WP_Term  $term     Hashtag term.
 * @param string[] $selected Ordered selected+enabled network slugs.
 * @return string
 */
function sh_render_hashtag_token( string $attrs, string $inner, WP_Term $term, array $selected ): string {
    $archive = get_term_link( $term );
    $archive = is_wp_error( $archive ) ? '' : $archive;

    $targets = sh_hashtag_targets( $term, $selected, $archive );

    // No enabled links: link to the archive or render as plain text, per setting.
    if ( empty( $targets ) ) {
        if ( 'plain' === sh_no_link_mode() || '' === $archive ) {
            return '<span class="sh-token sh-hashtag sh-token--plain">' . $inner . '</span>';
        }
        $attrs = sh_set_attr( $attrs, 'href', $archive );
        return '<a' . $attrs . '>' . $inner . '</a>';
    }

    // Exactly one target: the token links directly to it.
    if ( 1 === count( $targets ) ) {
        $t     = $targets[0];
        $attrs = sh_set_attr( $attrs, 'href', $t['url'] );
        if ( $t['external'] ) {
            $attrs = sh_set_text_attr( $attrs, 'rel', 'nofollow external noopener' );
            $attrs = sh_set_text_attr( $attrs, 'target', '_blank' );
        }
        return '<a' . $attrs . '>' . $inner . '</a>';
    }

    // Multiple targets: the token opens a pane listing them.
    $attrs = sh_set_attr( $attrs, 'href', '' !== $archive ? $archive : $targets[0]['url'] );
    $attrs = sh_add_class( $attrs, 'sh-token--multi' );
    $attrs = sh_set_text_attr( $attrs, 'role', 'button' );
    $attrs = sh_set_text_attr( $attrs, 'aria-haspopup', 'true' );
    $attrs = sh_set_text_attr( $attrs, 'aria-expanded', 'false' );

    $links = array();
    foreach ( $targets as $t ) {
        $rel     = $t['external'] ? ' rel="nofollow external noopener" target="_blank"' : '';
        $links[] = sprintf(
            '<a class="sh-pane__link sh-pane__link--%1$s" href="%2$s"%3$s>%4$s %5$s</a>',
            esc_attr( $t['slug'] ),
            esc_url( $t['url'] ),
            $rel,
            sh_network_icon_html( $t['slug'], $t['icon'], sh_network_color( $t['slug'] ) ),
            esc_html( $t['label'] )
        );
    }
    $pane = '<span class="sh-pane" hidden><span class="sh-pane__inner">' . implode( '', $links ) . '</span></span>';

    return '<span class="sh-token-wrap">' . '<a' . $attrs . '>' . $inner . '</a>' . $pane . '</span>';
}

/**
 * Builds the ordered link targets for a hashtag token.
 *
 * Each external network maps to its hashtag URL; the Blogosphere pseudo-network
 * maps to the local archive.
 *
 * @since 1.0.0
 * @param WP_Term  $term     Hashtag term.
 * @param string[] $selected Ordered selected+enabled network slugs.
 * @param string   $archive  Local archive URL (may be '').
 * @return array[] Each: { url, label, icon, slug, external }
 */
function sh_hashtag_targets( WP_Term $term, array $selected, string $archive ): array {
    $targets = array();
    foreach ( $selected as $slug ) {
        $def = sh_get_network( $slug );
        if ( ! $def ) {
            continue;
        }
        if ( ! empty( $def['internal'] ) ) {
            if ( '' === $archive ) {
                continue;
            }
            $url      = $archive;
            $external = false;
        } else {
            $url      = sh_build_network_url( $slug, $term->slug, 'hashtag' );
            $external = true;
        }
        if ( null === $url || '' === $url ) {
            continue;
        }
        $targets[] = array(
            'url'      => $url,
            'label'    => (string) $def['label'],
            'icon'     => (string) ( $def['icon'] ?? 'dashicons-admin-links' ),
            'slug'     => $slug,
            'external' => $external,
        );
    }
    return $targets;
}

/**
 * Resolves the term referenced by a token anchor (by ID, falling back to name).
 *
 * @since 1.0.0
 * @param string $attrs    Anchor attribute string.
 * @param string $taxonomy Taxonomy slug.
 * @return WP_Term|null
 */
function sh_resolve_token_term( string $attrs, string $taxonomy ): ?WP_Term {
    $id = (int) sh_token_attr( $attrs, 'data-sh-term' );
    if ( $id > 0 ) {
        $term = get_term( $id, $taxonomy );
        if ( $term instanceof WP_Term ) {
            return $term;
        }
    }
    $name = sh_token_attr( $attrs, 'data-sh-name' );
    if ( '' !== $name ) {
        $existing = term_exists( $name, $taxonomy );
        if ( $existing ) {
            $term = get_term( (int) ( is_array( $existing ) ? $existing['term_id'] : $existing ), $taxonomy );
            if ( $term instanceof WP_Term ) {
                return $term;
            }
        }
    }
    return null;
}

/**
 * Returns the ordered list of item slugs to render for a token, intersecting the
 * per-instance selection (data-sh-networks) with the given universe of selectable
 * items. A selection of '' or '*' means "all items in the universe".
 *
 * @since 1.0.0
 * @param string   $attrs    Anchor attribute string.
 * @param string[] $universe Ordered selectable item slugs for this token.
 * @return string[]
 */
function sh_token_selected_networks( string $attrs, array $universe ): array {
    $raw = trim( sh_token_attr( $attrs, 'data-sh-networks' ) );

    if ( '' === $raw || '*' === $raw ) {
        return $universe;
    }

    $selected = array_filter( array_map( 'trim', explode( ',', $raw ) ) );
    // Preserve the universe order.
    return array_values( array_intersect( $universe, $selected ) );
}

/**
 * The ordered selectable items for a mention token: enabled social networks plus,
 * when the Blogosphere network is enabled, the term's WordPress author profiles
 * (the "Local site" and any peers). Blogosphere itself is the on/off gate, not a
 * selectable item.
 *
 * @since 1.0.0
 * @param WP_Term $term Mention term.
 * @return string[]
 */
function sh_mention_universe( WP_Term $term ): array {
    $enabled = sh_get_enabled_networks( 'mention' ); // admin-defined settings order

    // The Blogosphere subrange: local profile first, then peers in Peer Sites order.
    $authors = ( in_array( 'blogosphere', $enabled, true ) && function_exists( 'tc_get_term_links' ) )
        ? sh_term_wp_author_slugs( tc_get_term_links( $term->term_id ) )
        : array();

    $universe = array();
    foreach ( $enabled as $slug ) {
        // Expand Blogosphere in place — it stands for the whole local + peer subrange.
        if ( 'blogosphere' === $slug ) {
            foreach ( $authors as $author_slug ) {
                $universe[] = $author_slug;
            }
            continue;
        }
        $def = sh_get_network( $slug );
        if ( $def && empty( $def['internal'] ) ) {
            $universe[] = $slug;
        }
    }

    return $universe;
}

/**
 * The WordPress author profile link-type slugs set on a term — the "Local site"
 * first, then peer sites — from a tc_get_term_links() map.
 *
 * @since 1.0.0
 * @param array $links Term links keyed by slug.
 * @return string[]
 */
function sh_term_wp_author_slugs( array $links ): array {
    $out = array();

    // Local profile first.
    if ( '' !== (string) ( $links['local_site'] ?? '' ) ) {
        $out[] = 'local_site';
    }

    // Then peer sites, in the TermConnect Peer Sites admin order.
    if ( function_exists( 'tc_get_platform_link_types' ) ) {
        foreach ( tc_get_platform_link_types( 'wordpress' ) as $slug => $type ) {
            if ( 'local_site' === $slug ) {
                continue;
            }
            if ( '' !== (string) ( $links[ $slug ] ?? '' ) ) {
                $out[] = $slug;
            }
        }
    }

    return $out;
}

/**
 * The human display name captured for a term's link, or '' when none is available.
 *
 * A local profile is resolved live from the WordPress user. For everything else the
 * name is read from the link's stored label (captured when picked from autocomplete,
 * formatted "{Type}: {Name} ({handle})") — there is no separate name store. Handles
 * entered by hand (networks without autocomplete) have no name.
 *
 * @since 1.0.0
 * @param int    $term_id Term ID.
 * @param string $slug    Link type slug.
 * @param string $handle  Stored handle/identifier.
 * @return string
 */
function sh_link_name( int $term_id, string $slug, string $handle ): string {
    // Local author: resolve the display name live (no parsing needed).
    if ( 'local_site' === $slug ) {
        $user = get_user_by( 'slug', $handle );
        $name = $user ? (string) $user->display_name : '';
        return ( '' !== $name && $name !== $handle ) ? $name : '';
    }

    $meta  = get_term_meta( $term_id, '_tc_link_' . $slug, true );
    $label = is_array( $meta ) ? (string) ( $meta['label'] ?? '' ) : '';
    if ( '' === $label ) {
        return '';
    }

    // Strip the "{Type}: " prefix and a trailing " (handle)" group.
    $type   = function_exists( 'tc_get_link_type' ) ? tc_get_link_type( $slug ) : null;
    $prefix = $type ? (string) ( $type['label'] ?? '' ) . ': ' : '';
    if ( '' !== $prefix && 0 === strpos( $label, $prefix ) ) {
        $label = substr( $label, strlen( $prefix ) );
    }
    $label = trim( (string) preg_replace( '/\s*\([^)]*\)\s*$/', '', $label ) );

    if ( '' === $label || $label === $handle || $label === '@' . $handle ) {
        return '';
    }
    return $label;
}

/**
 * Renders a mention token, mirroring the hashtag shape: a single enabled profile
 * renders inline as the network icon + handle (replacing the @name); several open
 * a pane of icon + handle rows; none links to the local archive or renders plain
 * (per the setting). A link to the local profile keeps the @name text.
 *
 * @since 1.0.0
 * @param string   $attrs    Anchor attribute string.
 * @param string   $inner    Anchor inner HTML (the visible @name).
 * @param WP_Term  $term     Mention term.
 * @param string[] $selected Ordered selected+enabled network slugs.
 * @return string
 */
function sh_render_mention_token( string $attrs, string $inner, WP_Term $term, array $selected ): string {
    $archive = get_term_link( $term );
    $archive = is_wp_error( $archive ) ? '' : $archive;

    $targets = sh_mention_targets( $term, $selected );

    // No enabled links: link to the local archive (the local profile) or render
    // as plain text, per the setting.
    if ( empty( $targets ) ) {
        if ( 'plain' === sh_no_link_mode() || '' === $archive ) {
            return '<span class="sh-token sh-mention sh-token--plain">' . $inner . '</span>';
        }
        $attrs = sh_set_attr( $attrs, 'href', $archive );
        return '<a' . $attrs . '>' . $inner . '</a>';
    }

    // Exactly one target.
    if ( 1 === count( $targets ) ) {
        $t     = $targets[0];
        $attrs = sh_set_attr( $attrs, 'href', $t['url'] );

        // A local-profile link keeps the @name text.
        if ( empty( $t['external'] ) ) {
            return '<a' . $attrs . '>' . $inner . '</a>';
        }

        // An external profile renders inline as the network icon + handle.
        $attrs = sh_set_text_attr( $attrs, 'rel', 'nofollow external noopener' );
        $attrs = sh_set_text_attr( $attrs, 'target', '_blank' );
        $attrs = sh_add_class( $attrs, 'sh-mention--inline' );
        $label = sh_network_icon_html( $t['slug'], $t['icon'], sh_network_color( $t['slug'] ) )
            . sh_mention_label_html( $t );
        return '<a' . $attrs . '>' . $label . '</a>';
    }

    // Multiple targets: the @name opens a pane listing each icon + handle.
    $attrs = sh_set_attr( $attrs, 'href', '' !== $archive ? $archive : $targets[0]['url'] );
    $attrs = sh_add_class( $attrs, 'sh-token--multi' );
    $attrs = sh_set_text_attr( $attrs, 'role', 'button' );
    $attrs = sh_set_text_attr( $attrs, 'aria-haspopup', 'true' );
    $attrs = sh_set_text_attr( $attrs, 'aria-expanded', 'false' );

    $links = array();
    foreach ( $targets as $t ) {
        $rel     = $t['external'] ? ' rel="nofollow external noopener" target="_blank"' : '';
        $links[] = sprintf(
            '<a class="sh-pane__link sh-pane__link--%1$s" href="%2$s"%3$s>%4$s %5$s</a>',
            esc_attr( $t['slug'] ),
            esc_url( $t['url'] ),
            $rel,
            sh_network_icon_html( $t['slug'], $t['icon'], sh_network_color( $t['slug'] ) ),
            sh_mention_label_html( $t )
        );
    }
    $pane = '<span class="sh-pane" hidden><span class="sh-pane__inner">' . implode( '', $links ) . '</span></span>';

    return '<span class="sh-token-wrap"><a' . $attrs . '>' . $inner . '</a>' . $pane . '</span>';
}

/**
 * Builds the ordered profile targets for a mention token from the selected items.
 *
 * Each item is either a social network (→ its stored handle's profile URL) or a
 * WordPress author profile link-type — the "Local site" (non-external, so a lone
 * one keeps the @name) or a peer (→ its /author/{nicename}/ archive).
 *
 * @since 1.0.0
 * @param WP_Term  $term     Mention term.
 * @param string[] $selected Ordered selected item slugs (from sh_mention_universe()).
 * @return array[] Each: { url, label, icon, slug, handle, external }
 */
function sh_mention_targets( WP_Term $term, array $selected ): array {
    $handles = function_exists( 'tc_get_term_links' ) ? tc_get_term_links( $term->term_id ) : array();
    $targets = array();

    foreach ( $selected as $slug ) {
        $def = sh_get_network( $slug );

        // Social network: link to the stored handle's profile.
        if ( $def && empty( $def['internal'] ) ) {
            $handle = (string) ( $handles[ 'social_' . $slug ] ?? '' );
            if ( '' === $handle ) {
                continue;
            }
            $url = sh_build_network_url( $slug, $handle, 'mention' );
            if ( null === $url || '' === $url ) {
                continue;
            }
            $targets[] = array(
                'url'      => $url,
                'label'    => (string) $def['label'],
                'icon'     => (string) ( $def['icon'] ?? 'dashicons-admin-links' ),
                'slug'     => $slug,
                'handle'   => $handle,
                'name'     => sh_link_name( $term->term_id, 'social_' . $slug, $handle ),
                'author'   => false,
                'external' => true,
            );
            continue;
        }

        // WordPress author profile (Local site or peer).
        if ( ! function_exists( 'tc_get_link_type' ) ) {
            continue;
        }
        $lt = tc_get_link_type( $slug );
        if ( ! $lt || 'wordpress' !== ( $lt['platform'] ?? '' ) ) {
            continue;
        }
        $id = (string) ( $handles[ $slug ] ?? '' );
        if ( '' === $id ) {
            continue;
        }
        $url = function_exists( 'tc_get_link_uri' ) ? tc_get_link_uri( $slug, $id, 'mention' ) : null;
        if ( null === $url || '' === $url ) {
            continue;
        }
        $is_local = ( 'local_site' === $slug );
        if ( ! $is_local && function_exists( 'tc_external_get_site_origin' ) && function_exists( 'tc_is_self_origin' ) ) {
            $origin   = tc_external_get_site_origin( (string) ( $lt['uri_prefix'] ?? '' ) );
            $is_local = ( '' !== $origin && tc_is_self_origin( $origin ) );
        }
        $targets[] = array(
            'url'      => $url,
            'label'    => sh_author_site_name( $slug, (string) ( $lt['label'] ?? $slug ) ),
            'icon'     => (string) ( $lt['icon'] ?? 'dashicons-admin-users' ),
            'slug'     => $slug,
            'handle'   => $id,
            'name'     => sh_link_name( $term->term_id, $slug, $id ),
            'author'   => true,
            'external' => ! $is_local,
        );
    }

    return $targets;
}

/**
 * The site name shown for a WordPress author profile. The non-configurable "Local
 * site" link type carries a generic label (fine in the term editor), so on the
 * front end and in the post editor we substitute this site's actual title; peers
 * already use their admin-given name.
 *
 * @since 1.0.0
 * @param string $slug     Link type slug.
 * @param string $fallback Link type label.
 * @return string
 */
function sh_author_site_name( string $slug, string $fallback ): string {
    if ( 'local_site' === $slug ) {
        $name = (string) get_bloginfo( 'name' );
        return '' !== $name ? $name : $fallback;
    }
    return $fallback;
}

/**
 * The visible text for a mention target: "Name @ Site" for a WordPress author
 * profile (local or peer), or "handle (Name)" for a social network.
 *
 * @since 1.0.0
 * @param array $t Target row from sh_mention_targets().
 * @return string HTML.
 */
function sh_mention_label_html( array $t ): string {
    if ( ! empty( $t['author'] ) ) {
        $name  = '' !== (string) ( $t['name'] ?? '' ) ? (string) $t['name'] : (string) $t['handle'];
        $inner = '<span class="sh-handle">' . esc_html( $name ) . '</span>'
            . ' @ <span class="sh-site">' . esc_html( (string) $t['label'] ) . '</span>';
    } else {
        $name  = ! empty( $t['name'] )
            ? ' <span class="sh-name">(' . esc_html( (string) $t['name'] ) . ')</span>'
            : '';
        $inner = '<span class="sh-handle">' . esc_html( (string) $t['handle'] ) . '</span>' . $name;
    }

    // Wrap as one inline label so the flex gap on the link/inline token applies only
    // between the icon and the text — not around the "@" or "(name)" inside it.
    return '<span class="sh-label">' . $inner . '</span>';
}

/**
 * Sets or replaces an attribute within an anchor attribute string.
 *
 * @since 1.0.0
 * @param string $attrs Attribute string (leading space preserved).
 * @param string $name  Attribute name.
 * @param string $value Raw value (will be escaped).
 * @return string
 */
function sh_set_attr( string $attrs, string $name, string $value ): string {
    $escaped     = esc_url( $value );
    $pattern     = '/\b' . preg_quote( $name, '/' ) . '=("|\').*?\1/i';
    $replacement = $name . '="' . $escaped . '"';
    if ( preg_match( $pattern, $attrs ) ) {
        return (string) preg_replace( $pattern, $replacement, $attrs, 1 );
    }
    return rtrim( $attrs ) . ' ' . $replacement;
}

/**
 * Sets or replaces a plain (non-URL) attribute within an attribute string.
 *
 * @since 1.0.0
 * @param string $attrs Attribute string.
 * @param string $name  Attribute name.
 * @param string $value Raw value (will be escaped).
 * @return string
 */
function sh_set_text_attr( string $attrs, string $name, string $value ): string {
    $replacement = $name . '="' . esc_attr( $value ) . '"';
    $pattern     = '/\b' . preg_quote( $name, '/' ) . '=("|\').*?\1/i';
    if ( preg_match( $pattern, $attrs ) ) {
        return (string) preg_replace( $pattern, $replacement, $attrs, 1 );
    }
    return rtrim( $attrs ) . ' ' . $replacement;
}

/**
 * Adds a class to the class attribute within an attribute string.
 *
 * @since 1.0.0
 * @param string $attrs Attribute string.
 * @param string $class Class to add.
 * @return string
 */
function sh_add_class( string $attrs, string $class ): string {
    if ( preg_match( '/\bclass=("|\')(.*?)\1/i', $attrs, $m ) ) {
        $classes = $m[2] . ' ' . $class;
        return (string) preg_replace( '/\bclass=("|\').*?\1/i', 'class="' . esc_attr( $classes ) . '"', $attrs, 1 );
    }
    return rtrim( $attrs ) . ' class="' . esc_attr( $class ) . '"';
}
